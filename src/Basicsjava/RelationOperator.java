package Basicsjava;

public class RelationOperator {
    public static void main(String[] args) {
        int a =22;
        int b = 10;
        int c = 30;

        System.out.println(a>b);
        System.out.println(c<b);
        System.out.println(a>=c);
        System.out.println(a<=b);
        System.out.println(c==b);
        System.out.println(a!=c);


    }
}
